#include <stdio.h>
#include <SDL3/SDL_main.h>

#include "config.h"
#include "gui.h"
#include "installer.h"

/// @brief メイン関数
/// @param argc 引数の数
/// @param argv 引数の配列
/// @return 正常終了時は0、エラー時は0以外
int main(int argc, char *argv[])
{
    (void)argc;
    (void)argv;

    // 設定をゼロ初期化
    LilConfig config = {0};

    // TOML設定ファイルを読み込む
    if (!lil_config_load("installer.toml", &config))
    {
        return 1;
    }

    #ifndef NDEBUG
    // インストール処理を実行
    LilInstallResult install_result = lil_install_file(
        "testdata/sample.txt",
        "testoutput/destination_file.txt"
    );

    if (install_result == LIL_INSTALL_OK)
    {
        printf("ファイルのコピーに成功しました。\n");
    }
    else
    {
        printf("ファイルのコピーに失敗しました。エラーコード: %d\n",
            (int)install_result);
    }
    #endif

    // GUIを起動
    int result = lil_gui_run(&config);

    // 設定データを解放
    lil_config_free(&config);

    return result;
}

